const round    = value => Math.round(value * 10) / 10
const pairs    = list => Array.from({ length: list.length / 2 }, (_, i) => [list[2 * i], list[2 * i + 1]])
const outwards = ([x, y], [cx, cy]) => {
  const length = Math.hypot(x - cx, y - cy)
  return [x + (x - cx) / length * END_EXTENSION, y + (y - cy) / length * END_EXTENSION]
}

// Pushes both ends 2.5 units along their tangents so the centers drawn on top hide the seam.
const extendEnds = (d) => {
  const points = pairs(d.match(/-?\d*\.?\d+/g).map(Number))
  const last   = points.length - 1
  points[0]    = outwards(points[0], points[1])
  points[last] = outwards(points[last], points[last - 1])
  const [start, ...rest] = points.map(point => point.map(round))
  const curves = Array.from({ length: rest.length / 3 }, (_, i) => rest.slice(3 * i, 3 * i + 3).map(p => p.join(' ')).join(' '))
  return `M${start.join(' ')} ${curves.map(curve => `C${curve}`).join(' ')}`
}

export const CHANNEL_LAYOUT = Object.fromEntries(
  Object.entries(CHANNEL_PATHS).map(([id, { length, d }]) => {
    const gates = id.split('-').map(Number)
    return [id, { id, gates, length, d: extendEnds(d), centers: gates.map(gate => GATE_CENTER[gate]) }]
  })
)

const groupBy = (entries, keysOf) => entries.reduce((index, entry) => {
  keysOf(entry).forEach(key => (index[key] ||= []).push(entry.id))
  return index
}, {})

const channels = Object.values(CHANNEL_LAYOUT)

export const CHANNELS_BY_GATE   = groupBy(channels, channel => channel.gates)
export const CHANNELS_BY_CENTER = groupBy(channels, channel => channel.centers)
